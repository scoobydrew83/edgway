/** Writing generated MDX: escaping, frontmatter and a stable write. */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

/** Where Kong's site-relative links (in its schema descriptions) point. */
const KONG_DOCS = "https://developer.konghq.com";

/**
 * Text safe inside MDX (and inside a Markdown table cell). Kong's
 * site-relative links (`](/gateway/…)`) become absolute, since this
 * site has no such pages.
 */
export const text = (value: unknown): string =>
  String(value ?? "")
    .replace(/\\/g, "\\\\")
    .replace(/[{}<>]/g, (c) => `\\${c}`)
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ")
    .replace(/\]\(\//g, `](${KONG_DOCS}/`);

/** Inline code (braces and angle brackets are literal inside it). */
export const code = (value: unknown): string =>
  `\`${String(value).replace(/\|/g, "\\|").replace(/`/g, "'")}\``;

/** A YAML string for frontmatter. */
const yaml = (value: string) => JSON.stringify(value);

export const frontmatter = (fields: Record<string, string>) =>
  [
    "---",
    ...Object.entries(fields).map(([k, v]) => `${k}: ${yaml(v)}`),
    "---",
    "",
  ].join("\n");

/** The banner on every generated page. */
export const GENERATED =
  "{/* Generated by tools/docs-gen. Do not edit: run `pnpm --filter @edgway/docs generate`. */}\n";

/** Replace a generated directory with exactly these files. */
export function writeDir(dir: string, files: Record<string, string>) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(path.join(dir, name), content);
  }
}
