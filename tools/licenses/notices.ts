/**
 * Third-party notices: for each production dependency of an
 * artifact, its name, version and licence, and the text of its licence and
 * NOTICE files as the package ships them, and the same for code copied into
 * a workspace package (`third-party/`). Generated, never hand-written.
 *
 * Usage: tsx tools/licenses/notices.ts <cli|ui|portal|workers> <output file>
 * `workers` is the gateway and admin Workers together: the committed
 * THIRD_PARTY_NOTICES.txt at the repository root, kept current by the
 * `licences` gate.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import {
  ARTIFACTS,
  type Artifact,
  bundledPackages,
  type LicenseReport,
  licenseReport,
  merge,
  packagesOf,
} from "./inventory";

/** The committed notices for the Workers (gateway and admin). */
export const WORKERS_NOTICES = "THIRD_PARTY_NOTICES.txt";

const LICENSE_FILE = /^(licen[cs]e|copying)([.-].*)?$/i;
const NOTICE_FILE = /^notice([.-].*)?$/i;

/** A package's files matching `pattern`, their text, in name order. */
function filesOf(dir: string | undefined, pattern: RegExp): string[] {
  if (!dir) return [];
  try {
    return readdirSync(dir)
      .filter((name) => pattern.test(name))
      .sort()
      .map((name) => readFileSync(path.join(dir, name), "utf8").trim());
  } catch {
    return [];
  }
}

/** The gateway's and the admin's production dependencies together. */
export const workersReport = () =>
  licenseReport([ARTIFACTS.gateway, ARTIFACTS.admin]);

/** The notices text for a report. */
export function notices(report: LicenseReport): string {
  const rule = "-".repeat(72);
  const parts = [
    "Third-party software notices",
    "",
    "This product includes the following third-party software. Each",
    "package's licence and NOTICE files are reproduced as it ships them.",
    "Generated by tools/licenses/notices.ts from pnpm's production",
    "dependency tree and the code copied into Edgway's packages (each",
    "package's third-party/ directory); do not edit by hand.",
  ];
  for (const pkg of packagesOf(report)) {
    const dir = pkg.paths[0];
    const texts = filesOf(dir, LICENSE_FILE);
    parts.push(
      "",
      rule,
      `${pkg.name} ${pkg.versions.join(", ")}`,
      `License: ${pkg.license}`,
      ...(pkg.homepage ? [`Homepage: ${pkg.homepage}`] : []),
      "",
      ...(texts.length > 0
        ? texts
        : [
            `(No licence file ships with the package; its licence is ${pkg.license}.)`,
          ]),
      ...filesOf(dir, NOTICE_FILE).flatMap((text) => ["", text]),
    );
  }
  return `${parts.join("\n")}\n`;
}

// Run as a script (not when the gate imports it).
const [target, output, metafile] = process.argv.slice(2);
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (!target || !output || !(target === "workers" || target in ARTIFACTS)) {
    console.error(
      "usage: notices.ts <cli|ui|portal|workers> <output> [esbuild metafile, for cli]",
    );
    process.exit(2);
  }
  let report =
    target === "workers"
      ? workersReport()
      : licenseReport([ARTIFACTS[target as Artifact]]);
  // The CLI also inlines its workspace packages' npm dependencies: the
  // bundle's metafile says which.
  if (metafile) report = merge(report, bundledPackages(metafile));
  // The directory may not exist yet: apps/ui/public holds only this
  // (gitignored) file, so a fresh checkout has no such directory.
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, notices(report));
  console.log(`notices: ${packagesOf(report).length} packages → ${output}`);
}
